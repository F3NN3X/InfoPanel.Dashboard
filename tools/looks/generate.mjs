// Writes the values that used to be copied by hand from their one source (src/looks/, src/lib/theme.ts) into the files
// that need them as literals: CSS that loads before any script, the gauge export's theme table, the Studio Look's
// `ui-*` chrome tokens (src/looks/studio/look.json, D1) and the Look registry (src/looks/ids.ts and index.ts, D5).
//   node tools/looks/generate.mjs           write the generated blocks and files
//   node tools/looks/generate.mjs --check   exit 1 and name the files that are out of date
// Each generated block opens with a do-not-edit header; tests/looks/generated.test.ts fails when one is stale.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { neededOf, scanUsage } from "./ui-usage.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const lf = (text) => text.replace(/\r\n/g, "\n");

const GENERATOR = "tools/looks/generate.mjs";
const header = (from) => `Generated by ${GENERATOR} from ${from}. Do not edit here: change the source and run \`npm run looks:gen\`.`;

/** Replaces the `@generated` block called `name` in `text` with `body` (lines), keeping the block's indent. */
function replaceBlock(text, name, from, body, indent = "") {
  const re = new RegExp(`[ \\t]*/\\* @generated:begin ${name}[\\s\\S]*?@generated:end ${name} \\*/`);
  if (!re.test(text)) throw new Error(`no "@generated:begin ${name}" block to fill`);
  const lines = [`/* @generated:begin ${name}`, `   ${header(from)} */`, ...body, `/* @generated:end ${name} */`];
  return text.replace(re, () => lines.map((l) => (l ? indent + l : l)).join("\n"));
}

const load = (rel) => import(pathToFileURL(join(root, rel)).href);
const read = (rel) => lf(readFileSync(join(root, rel), "utf8"));

/** The tokens of the generated status and shared sets each page's built files read now, by page (from the build; see ui-usage.mjs). */
export async function usageNow() {
  const studio = JSON.parse(read("src/looks/studio/look.json"));
  const names = [...Object.keys(studio.studio.shared), ...Object.keys(studio.studio.status)];
  return Object.fromEntries(Object.entries(scanUsage()).map(([page, reads]) => [page, neededOf(reads, names)]));
}

/** Every generated file: path (from the repo root) → its content with LF line ends. */
export async function generate() {
  const { STATUS, STATUS_LIGHT } = await load("src/looks/status.ts");
  const { DEFAULT_ACCENT, DARK_TEXT } = await load("src/looks/palette.ts");
  const { CLASSIC_T3, cssOf } = await load("src/looks/t3.ts");
  const { resolveT1, studioValue } = await load("src/looks/look.ts");
  const { SAMPLE_THEMES } = await load("src/looks/sample-themes.ts");
  const { DEFAULT_THEME } = await load("src/lib/theme.ts");
  const studio = JSON.parse(read("src/looks/studio/look.json"));
  const studioT1 = resolveT1(studio);
  const ui = (group) => Object.entries(studio.studio[group]).map(([name, entry]) => ({ name, entry, value: studioValue(entry, studioT1) }));
  const STUDIO = "the Studio Look (src/looks/studio/look.json)";
  const out = new Map();

  const css = "src/index.css";
  out.set(
    css,
    replaceBlock(read(css), "root-fallbacks", "DEFAULT_THEME (src/lib/theme.ts)", [
      ":root {",
      ...Object.entries(DEFAULT_THEME).map(([k, v]) => `  --${k}: ${v};`),
      "}",
    ]),
  );
  // Critical alert lines, rings and icons take the widgets' crit red (D7, owner call 5): the page's data-mode picks the light one.
  out.set(
    css,
    replaceBlock(out.get(css), "alert-critical", "STATUS and STATUS_LIGHT (src/looks/status.ts)", [
      ":root {",
      `  --alert-critical: ${STATUS.crit};`,
      "}",
      ":root[data-mode=light] {",
      `  --alert-critical: ${STATUS_LIGHT.crit};`,
      "}",
    ]),
  );
  // The chrome tokens only the studio's bundle uses; the shared ones and the status set are in tokens.css.
  out.set(css, replaceBlock(out.get(css), "studio-chrome", STUDIO, [":root {", ...ui("chrome").map((t) => `  --ui-${t.name}: ${t.value};`), "}"]));

  const tokens = "src/settings/tokens.css";
  out.set(
    tokens,
    replaceBlock(read(tokens), "studio-twins", STUDIO, [
      "@theme {",
      ...ui("shared").flatMap((t) => (t.entry.s ?? []).map((s) => `  --color-s-${s}: var(--ui-${t.name});`)),
      "}",
    ]),
  );
  // The tokens the twins and the status set name are declared in a stylesheet per page: the studio takes all of them, the
  // settings, help and touch pages only those their built files read (ui-usage.json, from tools/looks/ui-usage.mjs; L13).
  const usage = JSON.parse(read("tools/looks/ui-usage.json"));
  const tokenSet = [...ui("shared"), ...ui("status")];
  // One block over the whole file, so the D9 scans (tools/looks/scan.mjs) read it as generated.
  const pageCss = (page, tokensOf) =>
    [
      "/* @generated:begin ui-tokens",
      `   ${header(`${STUDIO}${page === "studio" ? "" : " and tools/looks/ui-usage.json"}`)} */`,
      "/* The one status set (Studio and Settings): ok, warn, danger. */",
      ":root {",
      ...tokensOf.map((t) => `  --ui-${t.name}: ${t.value};`),
      "}",
      "/* @generated:end ui-tokens */",
      "",
    ].join("\n");
  out.set("src/settings/ui/studio.css", pageCss("studio", tokenSet));
  for (const page of Object.keys(usage)) out.set(`src/settings/ui/${page}.css`, pageCss(page, tokenSet.filter((t) => usage[page].includes(t.name))));

  const mixer = "src/widgets/core/mixer-views.css";
  const t3 = (name) => cssOf(CLASSIC_T3[name]).toLowerCase();
  out.set(
    mixer,
    replaceBlock(
      read(mixer),
      "audiocn-status",
      "CLASSIC_T3 (src/looks/t3.ts)",
      [
        `--destructive: from ${t3("status-crit")} h s l;`,
        `--meter-ok: var(--wl-live, ${t3("meter-ok")});`,
        `--meter-ok-foreground: var(--wl-live, ${t3("meter-ok")});`,
        `--meter-warn: ${t3("meter-warn")};`,
        `--meter-clip: ${t3("meter-clip")};`,
        `--meter-clip-foreground: ${t3("meter-clip")};`,
        `--channel-mute: var(--wl-mute, ${t3("mute")});`,
        `--channel-mute-foreground: var(--wl-mute, ${t3("mute")});`,
      ],
      "  ",
    ),
  );

  const entry = (name, label, variable, hex) => `  ${name}: { label: "${label}", css: "var(--${variable}, ${hex.toUpperCase()})", hex: "${hex.toUpperCase()}" },`;
  out.set(
    "src/looks/generated/gauge-theme.ts",
    [
      `// ${header("src/looks/status.ts and palette.ts")}`,
      "",
      "/** The app's widget colours (src/widgets/core/theme.ts), with the dark-surface value used when baking. */",
      "export const THEME = {",
      entry("accent", "Accent", "w-accent", DEFAULT_ACCENT),
      entry("warn", "Warning", "w-warn", STATUS.warn),
      entry("crit", "Critical", "w-crit", STATUS.crit),
      entry("fg", "Text", "w-fg", DARK_TEXT.fg),
      entry("muted", "Muted text", "w-muted", DARK_TEXT.muted),
      `  track: { label: "Track", css: "color-mix(in oklab, var(--w-fg, #fff) 12%, transparent)", hex: "rgba(255,255,255,.12)" },`,
      "} as const;",
      "",
    ].join("\n"),
  );

  // The registry: every folder with a look.json but the Studio Look's, then the skins (one chunk, skins.ts) and the
  // sample Looks (one chunk, samples.ts). The ids alone are a module of their own, so a module that only checks an id
  // never pulls Classic's JSON into its bundle.
  const dirs = readdirSync(join(root, "src/looks"), { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "studio" && existsSync(join(root, "src/looks", d.name, "look.json")))
    .map((d) => d.name)
    .sort((a, b) => (a === "classic" ? -1 : b === "classic" ? 1 : a.localeCompare(b)));
  const packs = /SKIN_PACKS: SkinPack\[\] = \[([^\]]+)\]/.exec(read("src/widgets/core/theme.ts"))?.[1];
  if (!packs) throw new Error("no SKIN_PACKS list in src/widgets/core/theme.ts");
  const skins = packs.split(",").map((s) => s.trim().replace(/Skin$/, "")).filter((id) => id !== "default");
  const samples = SAMPLE_THEMES.map((t) => t.id);
  const list = (ids) => ids.map((id) => `"${id}"`).join(", ");
  // the font families of the built-in packs (their pack.json files): the validator refuses a user pack that claims one
  const packFamilies = [
    ...new Set(
      readdirSync(join(root, "src/looks/packs"), { withFileTypes: true })
        .filter((d) => d.isDirectory() && existsSync(join(root, "src/looks/packs", d.name, "pack.json")))
        .flatMap((d) => JSON.parse(read(`src/looks/packs/${d.name}/pack.json`)).fonts.map((f) => f.family)),
    ),
  ].sort();
  out.set(
    "src/looks/pack-fonts.ts",
    [
      `// ${header("src/looks/packs/*/pack.json")}`,
      "// Apart from ids.ts so the kiosk entry does not carry it: only the validator (a lazy chunk) reads it.",
      "",
      "/** The font families of the built-in packs (`pack.json`), which a user pack may not claim. */",
      `export const PACK_FONT_FAMILIES: readonly string[] = [${list(packFamilies)}];`,
      "",
    ].join("\n"),
  );
  out.set(
    "src/looks/ids.ts",
    [
      `// ${header("src/looks/*/look.json, SKIN_PACKS (src/widgets/core/theme.ts) and SAMPLE_THEMES (src/looks/sample-themes.ts)")}`,
      "// The Look ids (D5, D6): no Look data, so the kiosk can check an id without carrying a Look.",
      "",
      "/** The Look a level that sets none shows (`lookId` unset), and the one an unknown id falls back to. */",
      'export const CLASSIC_LOOK = "classic";',
      "",
      "/** The hidden Look a panel stored under the v16 `default` skin has: it draws the core Default skin, which Classic does not on a panel. No picker lists it. */",
      'export const DEFAULT_SKIN_LOOK = "default";',
      "",
      "/** The skins as Looks (config v17): a skin Look's id is the skin's name; the Default skin is Classic. */",
      `export const SKIN_LOOK_IDS: readonly string[] = [${list(skins)}];`,
      "",
      "/** The sample Looks (the P3b sample themes), all in one chunk. */",
      `export const SAMPLE_LOOK_IDS: readonly string[] = [${list(samples)}];`,
      "",
      "/** Every panel Look's id (the Studio Look is not one: only the studio chrome wears it). */",
      `export const LOOK_IDS: readonly string[] = [${list(dirs)}, DEFAULT_SKIN_LOOK, ...SKIN_LOOK_IDS, ...SAMPLE_LOOK_IDS];`,
      "",
      "/** The user packs the app data folder holds (P12b): ids the server listed, set by `registerUserLooks` before a config is read. Never a built-in's. */",
      "const USER_LOOK_IDS = new Set<string>();",
      "export const registerUserLooks = (ids: readonly string[], on = true): void => void ids.forEach((id) => (on ? USER_LOOK_IDS.add(id) : USER_LOOK_IDS.delete(id)));",
      "",
      "/** Whether a value names a Look of the registry or a user pack of the app data folder. */",
      "export const isLookId = (v: unknown): v is string => typeof v === \"string\" && (LOOK_IDS.includes(v) || USER_LOOK_IDS.has(v));",
      "",
    ].join("\n"),
  );
  out.set(
    "src/looks/index.ts",
    [
      `// ${header("src/looks/*/look.json")}`,
      "// The Look registry (D5): Classic is in the bundle, every other Look loads with import(). Importing this module",
      "// carries Classic's JSON: a module that only checks an id imports ./ids.",
      'import classic from "./classic/look.json";',
      'import { CLASSIC_LOOK, DEFAULT_SKIN_LOOK, SAMPLE_LOOK_IDS, SKIN_LOOK_IDS } from "./ids";',
      'import type { Look } from "./look";',
      "",
      'export { CLASSIC_LOOK, DEFAULT_SKIN_LOOK, isLookId, LOOK_IDS, SAMPLE_LOOK_IDS, SKIN_LOOK_IDS } from "./ids";',
      "",
      "/** The Classic Look's data. */",
      "export const CLASSIC = classic as Look;",
      "",
      "/** A Look by id (undefined: none); the hidden `default` Look has Classic's data; every other Look but Classic is in a chunk of its own (the skins, the samples). */",
      "export async function loadLook(id: string): Promise<Look | undefined> {",
      "  if (id === CLASSIC_LOOK || id === DEFAULT_SKIN_LOOK) return CLASSIC;",
      "  if (SKIN_LOOK_IDS.includes(id)) return (await import(\"./skins\")).SKIN_LOOKS[id];",
      "  return SAMPLE_LOOK_IDS.includes(id) ? (await import(\"./samples\")).SAMPLE_LOOKS[id] : undefined;",
      "}",
      "",
    ].join("\n"),
  );
  return out;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const check = process.argv.includes("--check");
  const usagePath = join(root, "tools/looks/ui-usage.json");
  // After `npm run build` and `npm run desktop:settings`: --from-build writes the tokens each page reads, --check-usage fails when the file differs.
  if (process.argv.includes("--from-build")) writeFileSync(usagePath, `${JSON.stringify(await usageNow(), null, 2)}
`);
  if (process.argv.includes("--check-usage")) {
    const now = await usageNow();
    const kept = JSON.parse(read("tools/looks/ui-usage.json"));
    const off = Object.keys(now).filter((page) => JSON.stringify(now[page]) !== JSON.stringify(kept[page]));
    if (off.length) {
      console.error(`tools/looks/ui-usage.json is out of date for ${off.join(", ")}: run \`npm run looks:gen -- --from-build\` after a build`);
      process.exit(1);
    }
    process.exit(0);
  }
  const stale = [];
  for (const [rel, content] of await generate()) {
    const path = join(root, rel);
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (lf(current) === content) continue;
    stale.push(rel);
    // Keep the file's own line ends (a Windows checkout has CRLF).
    if (!check) mkdirSync(dirname(path), { recursive: true });
    if (!check) writeFileSync(path, current.includes("\r\n") ? content.replace(/\n/g, "\r\n") : content);
  }
  if (check && stale.length) {
    console.error(`out of date, run \`npm run looks:gen\`: ${stale.join(", ")}`);
    process.exit(1);
  }
  if (!check) console.log(stale.length ? `wrote ${stale.join(", ")}` : "generated files are up to date");
}
