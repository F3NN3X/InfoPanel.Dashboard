// Writes the widget SDK's types, one downloadable .d.ts (Phase 6a; Gate 0 answer 6), from the real types: TypeScript emits the
// declarations of src/widgets/sdk.ts and of every file its declarations name, and each becomes a `declare module
// "infopanel-studio/<path>"` block; `infopanel-studio/widget-sdk` is the entry. The file is checked to compile before it is written.
//   node tools/widgets/sdk-types.mjs           write public/widget-sdk/infopanel-widget-sdk.d.ts
//   node tools/widgets/sdk-types.mjs --check   exit 1 when it is out of date
// Its header lists each source file with the SHA-256 of its text (line ends as LF): tests/tools/widgets/sdk-types.test.mjs fails,
// without running TypeScript, when one of them changed and the file was not written again.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, posix } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..").replace(/\\/g, "/");
export const OUT = "public/widget-sdk/infopanel-widget-sdk.d.ts";
const ENTRY = "src/widgets/sdk";
const NS = "infopanel-studio";

/** The SHA-256 of a source file's text with LF line ends. */
export const sourceHash = (rel) => createHash("sha256").update(readFileSync(join(root, rel), "utf8").replace(/\r\n/g, "\n")).digest("hex");

/** The `// source <path> <sha256>` lines of a written SDK file. */
export const listedSources = (text) => [...text.matchAll(/^\/\/ source (\S+) ([0-9a-f]{64})$/gm)].map((m) => ({ path: m[1], sha256: m[2] }));

const OPTIONS = (ts) => ({
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  jsx: ts.JsxEmit.ReactJSX,
  strict: true,
  skipLibCheck: true,
  baseUrl: root,
  paths: { "@/*": ["./src/*"] },
  rootDir: root,
  allowImportingTsExtensions: true,
  resolveJsonModule: true,
  types: [],
  lib: ["lib.es2022.d.ts", "lib.dom.d.ts", "lib.dom.iterable.d.ts"],
});

/** The SDK file's text. */
export function generate() {
  const ts = createRequire(join(root, "package.json"))("typescript");
  const program = ts.createProgram([`${root}/${ENTRY}.ts`], { ...OPTIONS(ts), declaration: true, emitDeclarationOnly: true, outDir: `${root}/.sdk-out` });
  const emitted = new Map();
  const result = program.emit(undefined, (file, text) => emitted.set(file.replace(/\\/g, "/").replace(`${root}/.sdk-out/`, "").replace(/\.d\.ts$/, ""), text), undefined, true);
  if (result.diagnostics.length) throw new Error(ts.formatDiagnostics(result.diagnostics, { getCanonicalFileName: (f) => f, getCurrentDirectory: () => root, getNewLine: () => "\n" }));
  const resolve = (from, spec) => {
    const base = spec.startsWith("@/") ? `src/${spec.slice(2)}` : spec.startsWith(".") ? posix.normalize(posix.join(posix.dirname(from), spec)) : null;
    if (base === null) return null;
    const path = base.replace(/\.(tsx?|js)$/, "");
    if (emitted.has(path)) return path;
    if (emitted.has(`${path}/index`)) return `${path}/index`;
    throw new Error(`${from}: ${spec} is not a file of the app`);
  };
  // The files the entry's declarations reach, in the order they are first named.
  const order = [];
  const queue = [ENTRY];
  while (queue.length) {
    const file = queue.shift();
    if (order.includes(file)) continue;
    order.push(file);
    for (const m of emitted.get(file).matchAll(/(?:from |import\()"([^"]+)"/g)) {
      const next = resolve(file, m[1]);
      if (next) queue.push(next);
    }
  }
  const sourceOf = (file) => [".ts", ".tsx"].map((ext) => `${file}${ext}`).find((p) => existsSync(join(root, p)));
  const blocks = order.map((file) => {
    const body = emitted
      .get(file)
      .replace(/^\/\/\/ <reference .*\n/gm, "")
      .replace(/(from |import\()"([^"]+)"/g, (all, head, spec) => {
        const target = resolve(file, spec);
        return target ? `${head}"${NS}/${target}"` : all;
      })
      .replace(/^(export )?declare /gm, "$1")
      .replace(/[ \t]+$/gm, "")
      .trimEnd()
      .replace(/^(?=.)/gm, "  ");
    return `declare module "${NS}/${file}" {\n${body}\n}\n`;
  });
  const sources = order.map(sourceOf).sort();
  return [
    "// InfoPanel Studio widget SDK: the types a code widget is built against (`defineWidget`, the bundle's contract, its props,",
    "// settings and primitives). Import from \"infopanel-studio/widget-sdk\"; the types name React's from your own @types/react.",
    `// Generated by tools/widgets/sdk-types.mjs from ${ENTRY}.ts. Do not edit: run \`node tools/widgets/sdk-types.mjs\`.`,
    ...sources.map((p) => `// source ${p} ${sourceHash(p)}`),
    "",
    `declare module "${NS}/widget-sdk" {\n  export * from "${NS}/${ENTRY}";\n}\n`,
    ...blocks,
  ].join("\n");
}

/** The TypeScript errors of an SDK file's text used the way a widget would use it, or `[]`. */
export function compileErrors(text) {
  const ts = createRequire(join(root, "package.json"))("typescript");
  const dir = join(root, ".cache", "widget-sdk-check");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "sdk.d.ts"), text);
  writeFileSync(join(dir, "use.ts"), 'import { defineWidget, type WidgetBundle } from "infopanel-studio/widget-sdk";\nconst bundle: WidgetBundle = (sdk) => sdk.defineWidget({ name: "x", reads: ["cpu."], defaultSize: [2, 2], render: ({ sensors }) => sdk.React.createElement(sdk.Ring, { value: sensors["cpu.load"]?.value }) });\nexport const used = [defineWidget, bundle];\n');
  const program = ts.createProgram([join(dir, "sdk.d.ts"), join(dir, "use.ts")], { ...OPTIONS(ts), skipLibCheck: false, noEmit: true, types: ["react"], typeRoots: [join(root, "node_modules/@types")], paths: {} });
  const own = ts.getPreEmitDiagnostics(program).filter((d) => !d.file || d.file.fileName.replace(/\\/g, "/").includes("/.cache/widget-sdk-check/"));
  return own.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
}

function main(args) {
  const text = generate();
  const errors = compileErrors(text);
  if (errors.length) {
    console.error(`the generated SDK does not compile:\n${errors.slice(0, 20).join("\n")}`);
    return 1;
  }
  const path = join(root, OUT);
  if (args.includes("--check")) {
    const stale = !existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text;
    if (stale) console.error(`${OUT} is out of date: run node tools/widgets/sdk-types.mjs`);
    return stale ? 1 : 0;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
  return 0;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) process.exitCode = main(process.argv.slice(2));
